"""
Write js/tracks.js from the 3D flights' window tracks (out/<home>-track3d.json, render_flight3d.py).

usage: python write_tracks.py [loft4 bung3]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

HEAD = """/* GENERATED by _work/flight/write_tracks.py from the 3D flights (render_flight3d.py).
   Per frame of the FORWARD flight (60 fps):
   frames[i] = the home window's box [u0, v0, u1, v1] in the 16:9 video frame (0..1);
   h[i] = the 3x3 homography (row major) taking a master px point (X, Y) of the home's facade
   (the 2560 x 1440 facade image) to the frame: w = h6 X + h7 Y + h8,
   u = (h0 X + h1 Y + h2) / w, v = (h3 X + h4 Y + h5) / w.
   For the reversed clip use index N - 1 - i. */
"""


def main():
    homes = sys.argv[1:] or ['loft4', 'bung3']
    out = {}
    for h in homes:
        t = json.load(open(os.path.join(HERE, 'out', f'{h}-track3d.json')))
        out[h] = {'fps': t['fps'], 'frames': t['frames'], 'h': t['h']}
    js = HEAD + 'const FLIGHT_TRACKS = ' + json.dumps(out, separators=(',', ':')) + ';\n'
    p = os.path.join(ROOT, 'js', 'tracks.js')
    open(p, 'w', encoding='utf-8').write(js)
    print('wrote', p, len(js) // 1024, 'KB', {h: len(out[h]['frames']) for h in out})


if __name__ == '__main__':
    main()
