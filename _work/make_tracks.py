"""
Per-frame window outline for each flight video -> ../js/tracks.js

The validator tracks the camera framing (cx, cy, w) of every frame. Raw tracks wobble by a
few pixels, so the framing is rebuilt as a smooth function of the measured zoom:
  log w(t): monotone, lightly smoothed
  centre(w): low-order fit of the tracked centres against k = (w - w1) / (w0 - w1),
             pinned to the exact master framing (k = 1) and the exact end framing (k = 0)
The window bay (ORIG coords) is then projected into each frame as normalised [u0, v0, u1, v1].

usage: python make_tracks.py loft4=takes/loft4_track.json bung3=takes/bung3_flight_joined.track.json
  (a .json from validate_video.py with 'rows', or a retime .track.json with 'frames')
"""
import json, sys
import numpy as np
from nestgeo import GEO, MASTER, tn_box_to_o, framing_of

out = {}
for arg in sys.argv[1:]:
    slug, path = arg.split('=')
    d = json.load(open(path))
    if 'rows' in d:
        rows = d['rows']; n = d['frames']
        idx = np.array([r['frame'] for r in rows], float)
        fr = np.array([[r['cx'], r['cy'], r['w']] for r in rows], float)
    else:
        fr = np.array(d['frames'], float); idx = np.arange(len(fr)); n = len(fr)
    start = np.array(framing_of(MASTER)); end = np.array(framing_of(tn_box_to_o(GEO[slug]['end'])))
    # zoom: monotone + light smoothing, exact at both ends
    lw = np.log(fr[:, 2]); lw[0] = np.log(start[2]); lw[-1] = np.log(end[2])
    lw = np.minimum.accumulate(lw)
    allf = np.arange(n)
    lw_all = np.interp(allf, idx, lw)
    ker = np.ones(5) / 5
    lw_s = np.convolve(np.pad(lw_all, 2, mode='edge'), ker, mode='valid')
    lw_s[0], lw_s[-1] = np.log(start[2]), np.log(end[2])
    w = np.exp(lw_s)
    # centre as a function of k, pinned at both ends: c(k) = end + (start - end) * k + k(1-k)(a + b k)
    k_obs = (fr[:, 2] - end[2]) / (start[2] - end[2])
    cs = []
    for dim in (0, 1):
        resid = fr[:, dim] - (end[dim] + (start[dim] - end[dim]) * k_obs)
        basis = np.stack([k_obs * (1 - k_obs), k_obs * k_obs * (1 - k_obs)], 1)
        coef, *_ = np.linalg.lstsq(basis, resid, rcond=None)
        k = (w - end[2]) / (start[2] - end[2])
        cs.append(end[dim] + (start[dim] - end[dim]) * k + k * (1 - k) * (coef[0] + coef[1] * k))
    cx, cy = cs
    h = w * 9 / 16
    X0, Y0, X1, Y1 = tn_box_to_o(GEO[slug]['bay'])
    rects = []
    for i in range(n):
        u0 = (X0 - (cx[i] - w[i] / 2)) / w[i]; u1 = (X1 - (cx[i] - w[i] / 2)) / w[i]
        v0 = (Y0 - (cy[i] - h[i] / 2)) / h[i]; v1 = (Y1 - (cy[i] - h[i] / 2)) / h[i]
        rects.append([round(u0, 5), round(v0, 5), round(u1, 5), round(v1, 5)])
    out[slug] = rects
    print(slug, n, 'frames; window at frame 0', rects[0], 'last', rects[-1])

with open('../js/tracks.js', 'w') as f:
    f.write('/* GENERATED by _work/make_tracks.py: the window bay, normalised to each flight frame [u0,v0,u1,v1]. */\n')
    f.write('const FLIGHT_TRACKS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
